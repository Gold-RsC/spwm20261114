size_t find_char_idx(uint8_t byte)
{
    if (byte >= 'a' && byte <= 'z')
    {
        return (byte - 'a');
    }
    if (byte >= 'A' && byte <= 'Z')
    {
        return (byte - 'A' + 26);
    }
    if (byte >= '0' && byte <= '9')
    {
        return (byte - '0' + 52);
    }
    switch(byte)
    {
        case '/':
            return 62;
        case '+':
            return 63;
        case '-':
            return 64;
        case '*':
            return 65;
        case '#':
            return 66;
        case '.':
            return 67;
        case ':':
            return 68;
    }
    return -1;
}
